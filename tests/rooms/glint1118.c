// №1118: хост-проверка блика на зеркале (viewer/mirrorglint.h): положение блика следует за камерой, зажим на краях, яркость и цвет полос.
// Красные контроли (обязаны упасть): -DGLINT_RED_SIGN (блик бежит против камеры), -DGLINT_RED_NOCLAMP (без зажима у крайней камеры)
#include <stdio.h>
#include <math.h>
#include "../../viewer/mirrorglint.h"
static int fails, total;
#define CHK(c, msg) do { total++; if (!(c)) { fails++; printf("FAIL %s\n", msg); } else printf("PASS %s\n", msg); } while (0)
int main(void) {
  // Moe's: центр панели по боковой оси 200,5, плоскость 54,88, середина высоты -18,275
  float c0 = glintPos(200.5f, 200.5f, 48.f, 54.88f, -18.275f, -18.275f, 0.f);
  float cl = glintPos(198.5f, 200.5f, 48.f, 54.88f, -18.275f, -18.275f, 0.f);
  float cr = glintPos(202.5f, 200.5f, 48.f, 54.88f, -18.275f, -18.275f, 0.f);
  CHK(fabsf(c0 - .5f) < 1e-5f, "камера против центра: блик посередине (0,5)");
  CHK(cl < c0 - .05f && cr > c0 + .05f, "камера влево на 2 м: блик левее, вправо: правее");
  float far_ = glintPos(300.f, 200.5f, 48.f, 54.88f, -18.275f, -18.275f, 0.f);
  CHK(far_ <= .5f + .5f * 1.3f + 1e-4f, "крайняя камера: блик не дальше 1,15 (зажим +-1,3)");
  float c3 = glintPos(200.5f, 200.5f, 48.f, 54.88f, -18.275f, -18.275f, 3.f);
  CHK(fabsf(c3 - c0 - .06f) < 1e-3f, "дрейф за 3 с: +0,06 (амплитуда)");
  float ch = glintPos(200.5f, 200.5f, 48.f, 54.88f, -17.275f, -18.275f, 0.f);
  CHK(fabsf(ch - c0 - .03f) < 1e-5f, "камера выше на метр: сдвиг 0,03");
  float near_ = glintPos(202.5f, 200.5f, 54.f, 54.88f, -18.275f, -18.275f, 0.f), far2 = glintPos(202.5f, 200.5f, 40.f, 54.88f, -18.275f, -18.275f, 0.f);
  CHK(near_ > far2, "ближе к стеклу смещение камеры даёт больший ход блика");
  // яркость
  float p = .55f;
  CHK(fabsf(glintH(p, .5f, p) - 1.f) < 1e-5f, "в центре главной полосы яркость 1");
  CHK(glintH(p + .5f, .5f, p) == 0.f && glintH(p - .6f, .5f, p) == 0.f, "вдали от полос яркость 0");
  CHK(fabsf(glintH(p - .34f, .5f, p) - .5f) < 1e-5f, "вторая полоса на 0,34 левее, вдвое слабее (0,5)");
  CHK(glintH(p + .1f, .0f, p) != glintH(p + .1f, 1.f, p), "полоса диагональная: низ и верх при одной u различаются");
  CHK(glintH(p, .5f, p) >= glintH(p + .1f, .5f, p) && glintH(p + .1f, .5f, p) >= glintH(p + .2f, .5f, p), "яркость падает от центра полосы");
  // цвет
  unsigned c_0 = glintColor(0.f), c_1 = glintColor(1.f);
  CHK((c_0 >> 24) == 40 && (c_0 & 255) == 150 && (c_0 >> 8 & 255) == 190 && (c_0 >> 16 & 255) == 235, "без блика: холодный оттенок (150,190,235), прозрачность 40 из 255");
  CHK((c_1 >> 24) == 160 && (c_1 & 255) == 255 && (c_1 >> 8 & 255) == 255 && (c_1 >> 16 & 255) == 255, "в центре блика: белый, прозрачность 160 из 255");
  printf("%s строк %d, упало %d\n", fails ? "FAIL" : "PASS", total, fails);
  return fails ? 1 : 0;
}
