// Шейп = n лучей (угол и длина у каждого свои — асимметрия). Кончики острые. Сторона между соседними кончиками T и T' — квадратичная кривая Безье с управляющей точкой
// Q = k · (T + T') / 2 (k у шейпа свой: .5 у четырёхлучевых, .4 у пятилучевого), то есть дуга ВОГНУТА К ЦЕНТРУ и гладкая (во впадине нет излома: внутренняя дуга округлая), а не прямая сторона ромба и не игла суперэллипса №937.
// k .5: впадина на 54 % радиуса кончика, угол при кончике около 37° — тело пухлое, кончик острый. k -> 1 — прямой ромб; k -> 0 — тонкая астроида (оба для красного контроля гейта: GS_KSCALE).
