#define GLINT944_OLD 0
#endif
#ifndef GS_KSCALE
#define GS_KSCALE 1.f   // красный контроль гейта: 1.9 — почти прямой ромб (кончик тупой), .3 — тонкая игла
#endif
#ifndef GS_MAXRAYS
#define GS_MAXRAYS 12   // №1261: свечение двери рисуется тем же шейпом, 10 лучей по контуру проёма (блик ключа: 4–5)
#endif
#define GS_MAXSEG 8
#define GS_MAXPTS (GS_MAXRAYS * GS_MAXSEG)
typedef struct { int n; float k, ang[GS_MAXRAYS], len[GS_MAXRAYS]; } GsDef;   // ang — по возрастанию, рад от +X против часовой; len — длина луча (доля радиуса звезды)
// стекло и звёзды частиц: четыре луча по осям, вертикальный 1,0, горизонтальный .85 (как sparkle ✨ №937)
// симметричный крест (звёзды частиц: поворачивается вместе с квадом)
static const GsDef GS_CROSS4 = {4, .5f, {0.f, 1.57079633f, 3.14159265f, 4.71238898f}, {1.f, 1.f, 1.f, 1.f}};
static const GsDef GS_SPARK4 = {4, .5f, {0.f, 1.57079633f, 3.14159265f, 4.71238898f}, {.85f, 1.f, .85f, 1.f}};
// блик в воздухе (ключ, трубка, «!», фары, искры): звезда A — четыре луча, чуть кривая крестовина и разные длины; звезда B — пять лучей, меньше и повёрнута
static const GsDef GS_GLINT_A = {4, .52f, {.06f, 1.62f, 3.20f, 4.70f}, {.80f, 1.f, .70f, .90f}};
static const GsDef GS_GLINT_B = {5, .40f, {.31f, 1.46f, 2.70f, 3.86f, 5.12f}, {.90f, 1.f, .96f, .80f, .92f}};
// контур: seg точек на сторону (первая — кончик), порядок против часовой; px, py — GS_MAXPTS; scale — общий масштаб. -> число точек = n * seg (замкнут: после последней идёт нулевая)
static inline int gsOutline(const GsDef *d, int seg, float scale, float *px, float *py) {
  if (seg > GS_MAXSEG) seg = GS_MAXSEG; if (seg < 1) seg = 1; int m = 0;
  for (int i = 0; i < d->n; i++) {
    int j = (i + 1) % d->n;
    float tx = cosf(d->ang[i]) * d->len[i], ty = sinf(d->ang[i]) * d->len[i], ux = cosf(d->ang[j]) * d->len[j], uy = sinf(d->ang[j]) * d->len[j];
    float kk = d->k * GS_KSCALE; if (kk > .98f) kk = .98f;
    float qx = (tx + ux) * .5f * kk, qy = (ty + uy) * .5f * kk;
    for (int k = 0; k < seg; k++) {
      float t = (float)k / (float)seg, a = (1.f - t) * (1.f - t), b = 2.f * t * (1.f - t), c = t * t;
      px[m] = (a * tx + b * qx + c * ux) * scale; py[m] = (a * ty + b * qy + c * uy) * scale; m++;
    }
  }
  return m;
}
