// №944 (Роб 24.10, ответ на №933 «светяшки на домах»): блики ВЗАИМОДЕЙСТВИЯ, что рисовались не этим шейпом (звезда входа в дом и магазин msnart.c doorStarVec и т.п.), — тот же шейп.
// GLINT944_OLD=1 — прежние формы этих мест
