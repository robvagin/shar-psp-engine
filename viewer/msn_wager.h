// Выплата = вход + целая часть (коэффициент машины игрока × вход). Целая часть = отбрасывание дробной (для коэффициентов 1,0 / 2,0 / 3,0 с диска разницы с округлением нет;
// для дробного, которого на диске нет, берём отбрасывание: так считает карточка оригинала). Коэффициент по умолчанию, пока машина не сообщила свой: L1–L5 2,0 (стартовые машины),
// L6–L7 1,0 (проверено по данным диска в круге 1).
#ifndef MSN_WAGER_H
#define MSN_WAGER_H
static inline int mvWagerPayOf(int fee, float odds) { return fee + (int)(odds * (float)fee); }
static inline float mvWagerOddsDefault(int level) { return level >= 6 ? 1.f : 2.f; }
#endif
