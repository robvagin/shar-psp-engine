// SVTELEPORT_OLD=1 — площадок нет.
int svTeleportCount(void);
int svTeleportAt(const float p[3]);                           // номер площадки, в объёме которой точка (центр тела игрока), -1 — нигде
int svTeleportTarget(int k, float pos[3], float *heading);    // куда ставить и курс (радианы, forward = (sin h, cos h)); 0 — номер неверный
// Сбросить состояние (смена уровня, рестарт миссии): множитель 1, счёт объёмов 0 — как сброс оригинала без перехода
void svLightReset(void);
