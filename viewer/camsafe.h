// Правка Роба 331 (04.10, голосом: «камера часто врезается по краям экрана, входит в текстуры — внутрь машин, домов, людей;
// после сильного удара с трамплина уходит под асфальт. Камера никогда не заходит за текстуры»). Правило порта для камер, которые
// ведёт сама игра (за машиной, пешком и переходы между ними), на всех уровнях:
//   1) ближняя плоскость кадра (у города 1,5 м: прямоугольник 3,2 × 1,8 м перед глазом при 62° и 16:9) — не дальше свободного
//      места перед глазом: 3 × 3 луча от глаза к углам, серединам сторон и центру ближней плоскости по коллизии мира (стены,
//      крыши, земля) и по телам (кузова машин, люди) — csNearFree. Края экрана больше не режут стену или кузов рядом;
//   2) глаз не за препятствием от опоры камеры (машина / Гомер), не ниже опоры коллизии под ним + запас, и вокруг глаза хватает
//      места хотя бы на CS_NEAR_MIN ближней плоскости — иначе глаз подъезжает к опоре (main.c camSafeEye). Наружу — сразу, назад —
//      плавно (без рывков).
// Чистый C99 поверх col.h (без PSP-заголовков) — гейт и харнесс на Маке собирают его как есть.
#ifndef SHAR_CAMSAFE_H
#define SHAR_CAMSAFE_H
#include "col.h"

#define CS_MAXBOX 112   // №727: + стейтпропы у глаза (own = 2)
#define CS_MAXCYL 40
#define CS_MAXTRI 3072   // №602: треугольники ВИДИМОЙ геометрии города у луча опора -> глаз (у картинки нет коллизии: карнизы, крыши, листва, вывески)
#define CS_NEAR_MIN .25f    // ближе ближняя плоскость не подходит (16-бит глубина: ближе — мерцание вдали; как у камеры пешком)
#define CAM_WALL_UP 3.f     // №922: м, на сколько высокие стены коллизии (здания) продолжены вверх для луча «опора -> глаз» (маска 128)
extern float colSegUp;   // col.c: добавка к верху высоких стен в raySeg, ставит только csRayFracC на время луча камеры
#define CS_GEOM_SKIP .8f    // луч опора -> глаз: первые .8 м сетка не смотрит (над крышей машины); лучи ближней плоскости — с 0
#define CS_NEAR_K .8f       // ближняя плоскость — эта доля свободного места перед глазом (запас на промежутки между лучами)

typedef struct { float x, z, fx, fz, hw, hl, y, gx, gz, lo, hi; int own; } CsBox;   // own — своя машина за рулём (от неё камера не уворачивается); own = 2 — стейтпроп: только для ближней плоскости (маска 32), глаз от него не уворачивается; own = 3 (№1127) — движущаяся чужая машина: как 2, но глаз в самой коробке (без запаса) негоден; csSkipMoving = 1 — такие коробки не видны вовсе (проверки глаза)
//   // кузов: как CarBox (пол Y = y + gx·dx + gz·dz, слой lo..hi)
typedef struct { float x, z, r, y0, y1; } CsCyl;                              // человек: вертикальный цилиндр
typedef struct {
  const ColWorld *w;
  CsBox box[CS_MAXBOX]; int nbox;
  CsCyl cyl[CS_MAXCYL]; int ncyl;
  float tri[CS_MAXTRI][9]; float (*geomRay)(const float a[3], const float b[3], float skip);   // сетка занятости (camgrid.h), 0 — нет
  int (*roofAbove)(const float p[3]);   // №922: над точкой p (верх стены) в пределах CAM_WALL_UP есть видимая геометрия (кусок города); 0 — продлевать всегда
  int ntri, useTri;   // useTri — правило использует треугольники (замер — всегда); мировые вершины; ntri = 0 — правило выключено (CAM_GEOM_OLD)
} CsScene;

// доля пути a -> b до первого препятствия: мир (bodies & 1), все тела (bodies & 2), чужие тела без своей машины за рулём (bodies & 4); тело, в котором начинается путь, не мешает
extern int csSkipMoving;   // №1127: 1 — движущиеся чужие машины (own = 3) не в счёт (правило глаза: положение камеры от них не меняется); 0 — ближняя плоскость их видит
extern int camNfStillOld; extern unsigned csNfStillHit;   // №984б: стоим — прошлый ответ csNearFree
extern int camRayBoxOld; extern unsigned csFiltBoxIn, csFiltBoxAll, csFiltCylIn, csFiltCylAll;   // №984: отсев тел шаром лучей (побитно тот же ответ)
extern int camRaysOld, camRaysVerify; extern unsigned csRaysMismatch;   // CAMPERF: пакетные лучи ближней плоскости (camsafe.c); verify — считает расхождения с лучами по одному
extern unsigned csRayCalls, csNfCalls;   // служебное (строка CAMSUB): сколько лучей и вызовов csNearFree за секунду
float csRayFrac(const CsScene *s, const float a[3], const float b[3], int bodies);
// доля пути a -> b до первого треугольника видимой геометрии (двусторонний тест)
float csTriFrac(const CsScene *s, const float a[3], const float b[3]);
// точка внутри тела (с запасом pad): 1 / 0
int csInBody(const CsScene *s, const float p[3], float pad);
// базис кадра: вперёд f (единичный), вправо r, вверх u — как у sceGumLookAt с up = (0, 1, 0)
void csBasis(const float f[3], float r[3], float u[3]);
// свободная глубина перед глазом: самая дальняя ближняя плоскость (<= nmax), при которой лучи от глаза к 3 × 3 точкам её
// прямоугольника не упираются ни во что; tanV = tan(fovy / 2), tanH = tanV * aspect
extern int camNearGeomOld;
extern int camNearDenseOld;   // №727: 1 — прежние 3 × 3 луча ближней плоскости
float csNearFree(const CsScene *s, const float eye[3], const float f[3], float tanV, float tanH, float nmax);

// Замер (гейт tests/camera/camin.py): что из прямоугольника ближней плоскости near и глаза внутри геометрии.
enum { CS_IN_EYE = 1,      // глаз за препятствием мира от опоры камеры (pivot) — внутри стены / за ней
       CS_IN_NEAR = 2,     // ближняя плоскость режет поверхность мира (луч глаз -> угол / середина стороны, стороны прямоугольника)
       CS_IN_GROUND = 4,   // глаз или угол ближней плоскости ниже опоры коллизии под ним (между точкой и высотой опоры камеры)
       CS_IN_CAR = 8,      // глаз в кузове или ближняя плоскость режет кузов машины
       CS_IN_PERSON = 16,  // то же для человека (прохожий, персонаж миссии, Гомер)
       CS_OCC_BODY = 32,  // (справочно) кузов/человек между опорой и глазом
       CS_IN_GEOM = 64,   // №602: между опорой и глазом ВИДИМАЯ геометрия города (карниз, крыша, листва, вывеска); не входит в «any» (& 31) // (справочно, не «внутри») кузов/человек между опорой и глазом
       // №791 (замер): ближняя плоскость режет ВИДИМУЮ геометрию (треугольники кусков города, flag camingeom 1): пол/асфальт (|ny| > 0,8) или стену
       CS_IN_VFLOOR = 128, CS_IN_VWALL = 256 };
int csProbe(const CsScene *s, const float eye[3], const float f[3], float tanV, float tanH, float near, const float pivot[3]);
extern float csDbgVf[4];   // №791 замер (csProbe): видимый пол x, y, z и коллизия под ним
#endif
