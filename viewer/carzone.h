typedef struct {
  int cur;              // камера прошлого кадра (-1 — камера за машиной)
  unsigned in, skip;    // маска «кузов в объёме» прошлого кадра; рельсы, не включившиеся на входе (до выхода из объёма)
  float eye[3], look[3], t;
  unsigned mid;         // №378: рельсы, в объёме которых побывала середина кузова (body[0]) за этот заход
  unsigned held;        // сверка g06: включившиеся камеры, держатся, пока кузов касается объёма (даже если скорость упала)
  float zoomH;          // сверка g06: текущий горизонтальный угол статичной камеры (авто-зум по расстоянию до машины)
} CarZoneState;

// кузов — точки (body[0] — середина коробки кузова, дальше её углы; оси движка); ref — начало модели машины; speed — горизонтальная
// скорость, м/с.
// Возврат: номер камеры (глаз, взгляд, вертикальный угол кадра) или -1 — снимает камера за машиной.
float carZoneSpeed(const float velocity[3]);   // скорость входа в рельс (по умолчанию полная, CARZONE_SPEED_OLD — горизонтальная)
int carZoneStep(const RoomCam *c, int n, CarZoneState *s, const float (*body)[3], int nbody, const float ref[3], float speed,
                float dt, float eye[3], float look[3], float *fovY);
